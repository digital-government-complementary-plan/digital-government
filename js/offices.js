  const toHalf = (s) => String(s == null ? "" : s).replace(/[０-９]/g, (d) => String.fromCharCode(d.charCodeAt(0) - 0xFEE0));
  // 郵便番号の数字だけ（全角も可）。7桁まで
  function normalizePostal(s) { return toHalf(s).replace(/[^0-9]/g, "").slice(0, 7); }
  // 「1234567」→「123-4567」
  function formatPostal(s) { const d = normalizePostal(s); return d.length > 3 ? d.slice(0, 3) + "-" + d.slice(3) : d; }
  // 郵便番号（3桁以上）から都道府県。分からなければ ""
  function prefFromPostal(s) {
    const d = normalizePostal(s);
    if (d.length < 3) return "";
    const n = parseInt(d.slice(0, 3), 10);
    for (const r of POSTAL) if (n >= r[0] && n <= r[1]) return r[2];
    return "";
  }
  // 住所の文字列の先頭にある都道府県（「〒123-4567」などは読み飛ばす）。なければ ""
  function stripLead(text) { return toHalf(text).replace(/^\s*〒?\s*[0-9\-－ー]*\s*/, ""); }
  function detectPref(text) {
    const t = stripLead(text);
    for (const p of PREFECTURES) if (t.startsWith(p)) return p;
    return "";
  }
  // 都道府県名を除いた、市区町村以下
  function afterPref(text) {
    const t = stripLead(text); const p = detectPref(t);
    return p ? t.slice(p.length) : t;
  }

  function bureausOf(pref) { return BUREAUS.filter((b) => b[1] === pref); }
  function bureauByName(name) { return BUREAUS.find((b) => b[0] === name) || null; }
  // 登記所（本局・支局・出張所）の一覧。名前は、「東京法務局板橋出張所」のように、法務局名＋庁名
  function officesOf(bureauName) {
    const b = bureauByName(bureauName);
    if (!b) return [];
    return b[2].map((o) => ({ name: b[0] + o[0], suffix: o[0], label: o[0] || "本局", areas: o[1].replace(/\*/g, ""), bureau: b[0], pref: b[1] }));
  }
  // 登記所の名前から、その法務局名（なければ ""）
  function bureauOfOffice(officeName) {
    const n = String(officeName || "").replace(/\s/g, "");
    let best = "";
    for (const b of BUREAUS) if (n.startsWith(b[0]) && b[0].length > best.length) best = b[0];
    return best;
  }

  // 管轄区域の文字列 → 市区町村の一覧（郡に続く町村は、「〇〇郡△△町」にそろえる。「*」は、市区町村の一部だけの管轄）
  function parseAreas(areas) {
    const out = [];
    let gun = "";
    String(areas || "").split("、").forEach((raw) => {
      let t = raw.trim();
      if (!t) return;
      const partial = t.endsWith("*"); t = t.replace(/\*+$/, "");
      const m = t.match(/^(.+?郡)(.*)$/);
      let bare = "";
      if (m) { gun = m[1]; bare = m[2]; }
      else if (/(市|区)$/.test(t)) gun = "";
      else if (/(町|村)$/.test(t) && gun) { bare = t; t = gun + t; }
      else gun = "";
      out.push({ text: t, bare: bare, partial: partial });
    });
    return out;
  }
  const tokenCache = {};
  function tokensOfPref(pref) {
    if (tokenCache[pref]) return tokenCache[pref];
    const list = [];
    bureausOf(pref).forEach((b) => officesOf(b[0]).forEach((o) => {
      parseAreas(b[2].find((x) => x[0] === o.suffix)[1]).forEach((t) => list.push({ text: t.text, bare: t.bare, partial: t.partial, office: o.name }));
    }));
    tokenCache[pref] = list;
    return list;
  }
  // 住所の先頭にある市区町村を調べる（最も長く一致するもの）。{ len: 一致した文字数, tokens: 一致した管轄区域の一覧 }
  function matchMunicipality(pref, rest) {
    let best = 0, hits = [];
    tokensOfPref(pref).forEach((t) => {
      let len = 0;
      if (rest.startsWith(t.text)) len = t.text.length;
      else if (t.bare && rest.startsWith(t.bare)) len = t.bare.length;     // 郡を省いて書かれている場合
      if (!len) return;
      if (len > best) { best = len; hits = [t]; } else if (len === best) hits.push(t);
    });
    return { len: best, tokens: hits };
  }
  // 住所（所在）から、管轄の登記所を調べる。
  //   state: unique（1つに決まる）／ambiguous（複数の登記所にまたがる）／none（判定できない）
  function findOffices(pref, text) {
    const rest = afterPref(text).replace(/^\s+/, "");
    if (!pref || !rest) return { state: "none", offices: [], municipality: "" };
    const m = matchMunicipality(pref, rest);
    if (!m.len) return { state: "none", offices: [], municipality: "" };
    const offices = Array.from(new Set(m.tokens.map((h) => h.office)));
    const municipality = rest.slice(0, m.len);
    if (offices.length === 1 && !m.tokens.some((h) => h.partial)) return { state: "unique", offices, municipality };
    return { state: "ambiguous", offices, municipality };
  }
  // 住所の先頭の市区町村（選択肢の値になる名前と、住所に書かれている文字数）。なければ { text: "", len: 0 }
  function municipalityOf(pref, text) {
    const rest = afterPref(text).replace(/^\s+/, "");
    const m = pref ? matchMunicipality(pref, rest) : { len: 0, tokens: [] };
    return m.len ? { text: m.tokens[0].text, len: m.len } : { text: "", len: 0 };
  }
  // どの都道府県のものでもよいので、住所の先頭が市区町村なら、その文字数と都道府県（都道府県が書かれていないとき用）
  function municipalityOfAny(rest) {
    let best = { len: 0, pref: "" };
    PREFECTURES.forEach((p) => { const m = matchMunicipality(p, rest); if (m.len > best.len) best = { len: m.len, pref: p }; });
    return best;
  }
  // 都道府県の市区町村の一覧（プルダウン用）。「市・区」、郡ごとの町村、「町・村」の順
  const muniCache = {};
  function municipalityGroups(pref) {
    if (!pref) return [];
    if (muniCache[pref]) return muniCache[pref];
    const cities = [], gun = {}, gunOrder = [], towns = [], seen = {};
    tokensOfPref(pref).forEach((t) => {
      if (seen[t.text]) return; seen[t.text] = true;
      if (t.bare) { const g = t.text.slice(0, t.text.length - t.bare.length); (gun[g] = gun[g] || []).push({ text: t.text, label: t.bare }); if (gunOrder.indexOf(g) < 0) gunOrder.push(g); }
      else if (/(市|区)$/.test(t.text)) cities.push({ text: t.text, label: t.text });
      else if (/郡$/.test(t.text)) { (gun[t.text] = gun[t.text] || []).push({ text: t.text, label: t.text + "（全域）" }); if (gunOrder.indexOf(t.text) < 0) gunOrder.push(t.text); }
      else towns.push({ text: t.text, label: t.text });
    });
    const out = [];
    if (cities.length) out.push({ name: "市・区", items: cities });
    gunOrder.forEach((g) => out.push({ name: g, items: gun[g] }));
    if (towns.length) out.push({ name: "町・村", items: towns });
    muniCache[pref] = out;
    return out;
  }

